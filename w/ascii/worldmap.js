const LAT0 = 78, LAT1 = -56;

function hash(n) { const s = Math.sin(n * 127.1) * 43758.5453; return s - Math.floor(s); }

function rasterize(cols, rows) {
  const SUB = 3;
  const cov = new Float32Array(cols * rows);
  const rowCov = new Float32Array(cols);
  const dLon = 360 / cols;
  for (let r = 0; r < rows; r++) {
    for (let sy = 0; sy < SUB; sy++) {
      rowCov.fill(0);
      const lat = LAT0 + (LAT1 - LAT0) * (r + (sy + 0.5) / SUB) / rows;
      for (const P of LAND) {
        const n = P.length / 2;
        const xs = [];
        for (let i = 0, j = n - 1; i < n; j = i++) {
          const yi = P[i * 2 + 1], yj = P[j * 2 + 1];
          if ((yi > lat) !== (yj > lat)) {
            const xi = P[i * 2], xj = P[j * 2];
            xs.push(xi + (lat - yi) * (xj - xi) / (yj - yi));
          }
        }
        if (xs.length < 2) continue;
        xs.sort((a, b) => a - b);
        for (let k = 0; k + 1 < xs.length; k += 2) {
          const a = (xs[k] + 180) / dLon, b = (xs[k + 1] + 180) / dLon;
          const c0 = Math.max(0, Math.floor(a)), c1 = Math.min(cols - 1, Math.floor(b));
          for (let c = c0; c <= c1; c++) {
            const ov = Math.min(b, c + 1) - Math.max(a, c);
            if (ov > 0) rowCov[c] = Math.min(1, rowCov[c] + ov);
          }
        }
      }
      for (let c = 0; c < cols; c++) cov[r * cols + c] += rowCov[c] / SUB;
    }
  }
  return cov;
}

export function initMap(canvas, opts = {}) {
  const ctx = canvas.getContext('2d');
  const base = document.createElement('canvas');
  const bctx = base.getContext('2d');
  let cols = 120, rows = 27, cw = 5, chh = 9, fs = 8, dpr = 1, landCells = [], W = 0;
  let arcs = [], flashes = [], running = false, visible = false, lastT = 0, labelN = 0;
  const onBlock = opts.onBlock || (() => {});

  const toCell = (lon, lat) => [((lon + 180) / 360) * cols, ((LAT0 - lat) / (LAT0 - LAT1)) * rows];

  function layout() {
    const par = canvas.parentElement, cs = getComputedStyle(par);
    const w = par.clientWidth - parseFloat(cs.paddingLeft) - parseFloat(cs.paddingRight);
    if (w <= 0 || Math.abs(w - W) < 1) return;
    W = w;
    dpr = Math.min(window.devicePixelRatio || 1, 2);
    cols = w < 420 ? 60 : (w < 700 ? 88 : 116);
    cw = w / cols;
    fs = cw / 0.6;
    chh = fs * 1.02;
    rows = Math.max(12, Math.round((w / (cols < 70 ? 1.75 : 2.1)) / chh));
    const h = rows * chh;
    canvas.style.height = h + 'px';
    canvas.width = Math.round(w * dpr); canvas.height = Math.round(h * dpr);
    base.width = canvas.width; base.height = canvas.height;
    const cov = rasterize(cols, rows);
    const land = (c, r) => (c < 0 || r < 0 || c >= cols || r >= rows) ? 0 : cov[r * cols + c];
    landCells = [];
    bctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    bctx.clearRect(0, 0, w, h);
    bctx.font = `700 ${fs.toFixed(2)}px "JetBrains Mono", ui-monospace, monospace`;
    bctx.textBaseline = 'top';
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        const v = land(c, r);
        const x = c * cw, y = r * chh;
        if (v < 0.16) {
          if (c % 3 === 0 && r % 2 === 0) { bctx.fillStyle = 'rgba(57,255,159,0.11)'; bctx.fillText('.', x, y); }
          continue;
        }
        const edge = land(c - 1, r) < 0.3 || land(c + 1, r) < 0.3 || land(c, r - 1) < 0.3 || land(c, r + 1) < 0.3;
        let ch, col;
        if (v < 0.42) { ch = ':'; col = 'rgba(57,255,159,0.42)'; }
        else if (edge) { ch = hash(c * 7 + r * 131) > 0.5 ? '*' : '+'; col = 'rgba(57,255,159,0.78)'; }
        else { const hh = hash(c * 13.1 + r * 71.7); ch = hh > 0.8 ? '%' : '#'; col = 'rgba(46,170,114,0.6)'; }
        if (v >= 0.42) landCells.push([c, r]);
        bctx.fillStyle = col; bctx.fillText(ch, x, y);
      }
    }
    draw(0);
  }

  function spawn() {
    if (!landCells.length) return;
    const s = landCells[Math.floor(Math.random() * landCells.length)];
    const t = CLIENTS[Math.floor(Math.random() * CLIENTS.length)];
    const [tx, ty] = toCell(t[0], t[1]);
    const sx = s[0] + 0.5, sy = s[1] + 0.5;
    const dx = tx - sx, dy = ty - sy;
    const dist = Math.hypot(dx, dy * 1.7);
    if (dist < 8) return;
    const lift = Math.min(rows * 0.45, dist * 0.32);
    arcs.push({ sx, sy, tx, ty, cx: (sx + tx) / 2, cy: Math.max(-1, (sy + ty) / 2 - lift), t: -Math.random() * 0.3, sp: 0.55 / Math.max(0.7, dist / 40) });
  }

  function put(ch, cx, cy, color, glow) {
    const c = Math.round(cx - 0.5), r = Math.round(cy - 0.5);
    if (c < 0 || r < 0 || c >= cols || r >= rows) return;
    if (glow) { ctx.shadowColor = color; ctx.shadowBlur = glow; } else ctx.shadowBlur = 0;
    ctx.fillStyle = color;
    ctx.fillText(ch, c * cw, r * chh);
  }

  function draw(now) {
    const w = canvas.width / dpr, h = canvas.height / dpr;
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    ctx.drawImage(base, 0, 0);
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.font = `800 ${fs.toFixed(2)}px "JetBrains Mono", ui-monospace, monospace`;
    ctx.textBaseline = 'top';
    const tt = now / 1000;
    // SOC sites
    for (const s of SOC) {
      const [x, y] = toCell(s.lon, s.lat);
      put('[', x - 1, y, '#39ff9f', 6); put('#', x, y, '#39ff9f', 10); put(']', x + 1, y, '#39ff9f', 6);
    }
    ctx.shadowBlur = 0;
    // clients
    for (const c of CLIENTS) {
      const [x, y] = toCell(c[0], c[1]);
      put('@', x, y, 'rgba(230,255,243,0.9)', 0);
    }
    // arcs
    for (const a of arcs) {
      if (a.t < 0) continue;
      const p = Math.min(1, a.t);
      for (let k = 10; k >= 0; k--) {
        const q = p - k * 0.03;
        if (q < 0) continue;
        const u = 1 - q;
        const x = u * u * a.sx + 2 * u * q * a.cx + q * q * a.tx;
        const y = u * u * a.sy + 2 * u * q * a.cy + q * q * a.ty;
        if (k === 0) put('*', x, y, '#ff3b3b', 12);
        else put(k < 3 ? '+' : '.', x, y, `rgba(255,59,59,${(0.9 - k * 0.075).toFixed(2)})`, 0);
      }
      if (p < 0.45 && Math.floor(tt * 6) % 2 === 0) put('x', a.sx, a.sy, '#ff3b3b', 8);
    }
    // impact flashes
    for (const f of flashes) {
      const r = 1 + f.life * 3.2;
      const al = Math.max(0, 1 - f.life);
      for (let i = 0; i < 10; i++) {
        const an = (i / 10) * Math.PI * 2;
        put('.', f.x + Math.cos(an) * r, f.y + Math.sin(an) * r * 0.55, `rgba(230,255,243,${al.toFixed(2)})`, 0);
      }
      if (f.life < 0.75 && f.label && cols >= 70) {
        ctx.shadowBlur = 0;
        const lf = Math.max(9, fs * 1.05);
        ctx.font = `700 ${lf.toFixed(1)}px "JetBrains Mono", ui-monospace, monospace`;
        const tw = ctx.measureText('BLOCKED').width;
        const lx = Math.min(w - tw - 6, Math.max(2, f.x * cw - tw / 2)), ly = Math.max(1, (f.y - 2.4) * chh);
        ctx.fillStyle = `rgba(3,9,6,${Math.min(0.9, al * 1.3).toFixed(2)})`;
        ctx.fillRect(lx - 3, ly - 2, tw + 6, lf + 4);
        ctx.fillStyle = `rgba(57,255,159,${Math.min(1, al * 1.4).toFixed(2)})`;
        ctx.fillText('BLOCKED', lx, ly);
        ctx.font = `800 ${fs.toFixed(2)}px "JetBrains Mono", ui-monospace, monospace`;
      }
    }
    ctx.shadowBlur = 0;
    // SOC labels last so they sit on top
    const sf = Math.max(9, fs * 1.0);
    if (cols < 70) return;
    ctx.font = `700 ${sf.toFixed(1)}px "JetBrains Mono", ui-monospace, monospace`;
    for (const s of SOC) {
      const [x, y] = toCell(s.lon, s.lat);
      const tw = ctx.measureText(s.label).width;
      let lx = (x + 2.2) * cw;
      if (lx + tw > w - 4) lx = (x - 2.2) * cw - tw;
      const ly = Math.min(h - sf - 2, (y + 1.1) * chh);
      ctx.fillStyle = 'rgba(3,9,6,0.88)';
      ctx.fillRect(lx - 3, ly - 2, tw + 6, sf + 4);
      ctx.fillStyle = 'rgba(57,255,159,0.95)';
      ctx.fillText(s.label, lx, ly);
    }
  }

  function step(now) {
    if (!running) return;
    requestAnimationFrame(step);
    if (now - lastT < 90) return;
    const dt = lastT ? Math.min(0.2, (now - lastT) / 1000) : 0.09;
    lastT = now;
    const target = opts.mobile ? 4 : 7;
    while (arcs.length < target) spawn();
    for (const a of arcs) a.t += a.sp * dt;
    for (let i = arcs.length - 1; i >= 0; i--) {
      if (arcs[i].t >= 1) { flashes.push({ x: arcs[i].tx, y: arcs[i].ty, life: 0, label: (labelN++ % 2) === 0 }); arcs.splice(i, 1); onBlock(); }
    }
    for (const f of flashes) f.life += dt * 0.9;
    flashes = flashes.filter((f) => f.life < 1);
    draw(now);
  }

  function setVisible(v) {
    visible = v;
    if (v && !running) { running = true; lastT = 0; requestAnimationFrame(step); }
    if (!v) running = false;
  }

  layout();
  // seed a few arcs mid-flight so the first frame is already alive
  for (let i = 0; i < (opts.mobile ? 4 : 7); i++) spawn();
  arcs.forEach((a, i) => { a.t = 0.15 + (i / arcs.length) * 0.7; });
  draw(performance.now());
  const ro = new ResizeObserver(() => layout());
  ro.observe(canvas.parentElement);
  const io = new IntersectionObserver((e) => setVisible(e[0].isIntersecting), { rootMargin: '60px' });
  io.observe(canvas);
  return { relayout: () => { W = 0; layout(); } };
}
